import os
import cv2
import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
from skimage import io
from scipy.stats import wasserstein_distance

def analyze_separability(raw_dir, mask_dir, prep_dir, target_size=(512, 512)):
    """
    Quantifies how much the preprocessing improved the statistical
    separation between target cells (Osteoclasts) and background debris.
    """
    print("🔬 RUNNING SEPARABILITY DIAGNOSIS (Target vs. Distractors)...")

    # Tracking data
    raw_distances = []
    prep_distances = []

    # Filter for image files
    files = sorted([f for f in os.listdir(raw_dir) if f.lower().endswith(('.tif', '.png', '.jpg'))])

    # Process a representative sample (50 images) for statistical significance
    sample_files = files[:50]

    for fname in sample_files:
        base = os.path.splitext(fname)[0]

        # 1. Path Construction
        raw_path = os.path.join(raw_dir, fname)
        # Check for multiple possible mask extensions
        mask_path = None
        for ext in ['_mask.png', '_mask.tif', '.png', '.tif']:
            p = os.path.join(mask_dir, base + ext)
            if os.path.exists(p):
                mask_path = p
                break

        prep_path = os.path.join(prep_dir, base + '.png')

        if not mask_path or not os.path.exists(prep_path):
            continue

        # 2. Load and Prepare Data
        try:
            # Raw Data: Convert to LAB and extract Luminance (L)
            raw = io.imread(raw_path)
            if raw.ndim == 2: raw = cv2.cvtColor(raw, cv2.COLOR_GRAY2RGB)
            elif raw.shape[2] == 4: raw = raw[:,:,:3]
            raw = cv2.resize(raw, target_size)
            raw_l = cv2.cvtColor(raw, cv2.COLOR_RGB2LAB)[:,:,0]

            # Preprocessed Data: Extract Luminance
            prep_img = cv2.imread(prep_path)
            prep_l = cv2.cvtColor(prep_img, cv2.COLOR_BGR2LAB)[:,:,0]

            # Ground Truth Mask
            mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
            mask = cv2.resize(mask, target_size, interpolation=cv2.INTER_NEAREST)
            mask_bin = (mask > 0).astype(np.uint8)

            # 3. Create "Distractor" Mask
            # Use Otsu's thresholding to find all non-background stained tissue
            _, all_tissue = cv2.threshold(raw_l, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

            # Distractors = (Everything Stained) - (True Expert-Labeled Osteoclasts)
            # This isolates the debris and stem cells the AI might confuse with osteoclasts
            distractors = cv2.bitwise_and(all_tissue, all_tissue, mask=(1-mask_bin).astype(np.uint8))

            # 4. Extract Pixel Distributions
            raw_target_pix = raw_l[mask_bin == 1]
            raw_distractor_pix = raw_l[distractors > 0]

            prep_target_pix = prep_l[mask_bin == 1]
            prep_distractor_pix = prep_l[distractors > 0]

            # Ensure we have enough pixels to compare
            if len(raw_target_pix) < 10 or len(raw_distractor_pix) < 10:
                continue

            # 5. Measure Statistical Distance (Wasserstein)
            # Higher distance = cleaner signal for the U-Net to learn
            d_raw = wasserstein_distance(raw_target_pix, raw_distractor_pix)
            d_prep = wasserstein_distance(prep_target_pix, prep_distractor_pix)

            raw_distances.append(d_raw)
            prep_distances.append(d_prep)

        except Exception as e:
            continue

    # --- PLOT & REPORT RESULTS ---
    if not raw_distances:
        print("❌ ERROR: No matching files found. Check your directory paths.")
        return

    plt.figure(figsize=(10, 6))
    plot_df = pd.DataFrame({
        'Distance': raw_distances + prep_distances,
        'Condition': ['Raw Input'] * len(raw_distances) + ['OCLAST Preprocessed'] * len(prep_distances)
    })

    sns.boxplot(x='Condition', y='Distance', data=plot_df, palette="husl")
    plt.title("Preprocessing Efficacy: Osteoclasts vs. Biological Noise", fontsize=14, fontweight='bold')
    plt.ylabel("Wasserstein Distance (Separability Score)")
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.show()

    avg_raw = np.mean(raw_distances)
    avg_prep = np.mean(prep_distances)
    improvement = ((avg_prep - avg_raw) / avg_raw) * 100

    print(f"\n" + "="*50)
    print(f"📊 DATA SEPARABILITY SUMMARY")
    print(f"="*50)
    print(f"Baseline Separability (Raw):      {avg_raw:.2f}")
    print(f"Enhanced Separability (Prep):     {avg_prep:.2f}")
    print(f"Mathematical Signal Boost:        {improvement:.1f}%")
    print("-" * 50)

    if avg_prep > avg_raw:
        print(f"✅ SUCCESS: Preprocessing enhanced the biological signal by {improvement:.1f}%.")
    else:
        print("⚠️ WARNING: Preprocessing reduced separability. Check Contrast/CLAHE settings.")

