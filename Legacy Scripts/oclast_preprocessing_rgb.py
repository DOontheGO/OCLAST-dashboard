# Cell 3: V9 "Nuclear Pop" Preprocessing (Top-Hat + CLAHE)

def surgical_rgb_enhance(image_path, target_size=(512, 512)):
    """
    V9 Pipeline:
    1. Robust Load & Resize.
    2. Convert to LAB.
    3. L-Channel CLAHE (Global Contrast).
    4. L-Channel White Top-Hat (Highlight 'Lighter' Nuclei).
    5. Fusion: Add Top-Hat signal to enhanced L-Channel.
    6. Merge & Return RGB.
    """
    # --- 1. Robust Loading ---
    img = None
    try:
        img = io.imread(image_path)
        if img.ndim == 2: img = cv2.cvtColor(img, cv2.COLOR_GRAY2RGB)
        elif img.shape[2] == 4: img = img[:, :, :3]
    except:
        try:
            pil_img = Image.open(image_path).convert('RGB')
            img = np.array(pil_img)
        except: return None

    if img is None: return None
    img = cv2.resize(img, target_size, interpolation=cv2.INTER_AREA)

    # --- 2. Color Space Conversion ---
    # We work in LAB to decouple "Lightness" (Structure) from "Color" (Chemistry)
    lab = cv2.cvtColor(img, cv2.COLOR_RGB2LAB)
    l, a, b = cv2.split(lab)

    # --- 3. Step A: Global Contrast (CLAHE) ---
    # This sets the stage by fixing lighting drift
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    l_clahe = clahe.apply(l)

    # --- 4. Step B: "Hole" Extraction (White Top-Hat) ---
    # We define a "kernel" size roughly the size of a nucleus (e.g., 15x15 pixels)
    # This filter finds "bright things approx 15px wide"
    kernel_size = (15, 15)
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, kernel_size)

    # Apply White Top-Hat: Extracts BRIGHT objects on DARK background
    nuclei_map = cv2.morphologyEx(l_clahe, cv2.MORPH_TOPHAT, kernel)

    # --- 5. Step C: Fusion (Accentuate) ---
    # We ADD the nuclei map back to the image.
    # This makes the "lighter" nuclei significantly brighter.
    # alpha=1.0 (Base), beta=1.5 (Boost factor for nuclei)
    l_final = cv2.addWeighted(l_clahe, 1.0, nuclei_map, 0.8, 0)

    # Merge back
    lab_merged = cv2.merge((l_final, a, b))
    final_img = cv2.cvtColor(lab_merged, cv2.COLOR_LAB2RGB)

    return final_img

print("✅ V9 Pipeline Defined: Includes Top-Hat Morphological Boosting.")

